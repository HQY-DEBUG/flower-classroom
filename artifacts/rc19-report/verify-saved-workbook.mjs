import fs from 'node:fs/promises';
import crypto from 'node:crypto';
import assert from 'node:assert/strict';
import {SpreadsheetFile,FileBlob} from '@oai/artifact-tool';
const [file,input,out]=process.argv.slice(2),d=JSON.parse(await fs.readFile(input,'utf8'));
const w=await SpreadsheetFile.importXlsx(await FileBlob.load(file));w.recalculate();
const r=w.worksheets.getItem('功能验收');
assert.deepEqual(r.getRange('A6:A198').values.flat(),d.requirements.map(q=>q.id));
assert.deepEqual(r.getRange('G6:G198').values.flat(),d.requirements.map(q=>q.status));
assert(r.getRange('G6:G198').formulas.flat().every(Boolean));
assert.deepEqual(w.worksheets.getItem('用户操作旅程').getRange('H6:H16').values.flat(),d.journeys.map(j=>j.status));
const final=d.runs.filter(r=>r.stage==='最终冻结').flatMap(r=>r.checks);
assert.equal(final.length,6278);
assert.deepEqual(w.worksheets.getItem('最终断言').getRange('D6:D6283').values.flat(),final.map(c=>c.name));
assert.deepEqual(w.worksheets.getItem('最终断言').getRange('E6:E6283').values.flat(),final.map(c=>c.status==='passed'?'通过':'仅观察'));
assert.deepEqual(w.worksheets.getItem('缺陷与修复').getRange('J6:J8').values.flat(),Array(3).fill('已修复并复验'));
assert.deepEqual(w.worksheets.getItem('验证概览').getRange('B6:F6').values[0],[184,0,0,9,193]);
assert.deepEqual(w.worksheets.getItem('验证概览').getRange('B11:F11').values[0],[6270,0,8,6278,0]);
const result={xlsxSha256:crypto.createHash('sha256').update(await fs.readFile(file)).digest('hex'),reportInputSha256:crypto.createHash('sha256').update(await fs.readFile(input)).digest('hex'),tool:'Artifact Tool importXlsx and recalculate',requiredStatusesAndFormulasVerified:193,finalAssertionExactNamesAndStatusesVerified:6278,journeysVerified:11,closedFindingFormulasVerified:3,summaryTotalsVerified:true,nativeExcelWpsVerified:false,status:'passed'};
await fs.writeFile(out,JSON.stringify(result,null,2)+'\n');console.log(JSON.stringify(result));
